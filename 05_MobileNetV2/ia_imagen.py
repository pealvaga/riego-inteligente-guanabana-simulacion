IMG_SIZE = 224


def cargar_imagen(
    ruta,
    etiqueta
):

    imagen = tf.io.read_file(
        ruta
    )

    imagen = tf.io.decode_image(
        imagen,
        channels=3,
        expand_animations=False
    )

    imagen.set_shape(
        [None, None, 3]
    )

    imagen = tf.image.resize(
        imagen,
        [IMG_SIZE, IMG_SIZE]
    )

    imagen = tf.cast(
        imagen,
        tf.float32
    )

    etiqueta = tf.cast(
        etiqueta,
        tf.float32
    )

    return imagen, etiqueta


