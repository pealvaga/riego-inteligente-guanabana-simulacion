import math
from datetime import datetime

import joblib
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import sklearn

from google.colab import files
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score
)

# ============================================================
# 1. CARGAR BASE DE DATOS
# ============================================================

print("Seleccione Datos_entrenamiento_guanabana.xlsx")

archivos = files.upload()

if not archivos:
    raise ValueError("No se seleccionó ningún archivo.")

nombre_archivo = next(iter(archivos))

VERSION_SIMULADOR = "balance_hidrico_temperatura_v2"

OBJETIVO = "HumedadObjetivo_10min"


# Verificar versión del simulador

parametros = pd.read_excel(
    nombre_archivo,
    sheet_name="Parametros"
)

configuracion = dict(zip(
    parametros["Parametro"].astype(str).str.strip(),
    parametros["Valor"].astype(str).str.strip()
))

if configuracion.get("Version del simulador") != VERSION_SIMULADOR:
    raise ValueError(
        "Este Excel no corresponde al nuevo balance hídrico. "
        "Exporta los datos desde la aplicación actualizada."
    )


# Leer únicamente la hoja de entrenamiento

df = pd.read_excel(
    nombre_archivo,
    sheet_name="Entrenamiento_RF"
)

print("\nArchivo cargado correctamente.")
print("Registros encontrados:", len(df))

# ============================================================
# 2. SELECCIONAR VARIABLES DEL MODELO
# ============================================================

variables_modelo = [

    # Estado actual
    "Temperatura",
    "Precipitacion",
    "HumedadSuelo",
    "RiegoActivo",

    # Humedad histórica
    "HumedadSuelo_lag1",
    "HumedadSuelo_lag2",

    # Temperatura histórica
    "Temperatura_lag1",
    "Temperatura_lag2",

    # Precipitación histórica
    "Precipitacion_lag1",
    "Precipitacion_lag2",

    # Estado del riego histórico
    "RiegoActivo_lag1",
    "RiegoActivo_lag2"
]


# Sesion y MinutoTotal solo sirven para ordenar.
# No se utilizan como variables de entrenamiento.

columnas_requeridas = (
    variables_modelo
    + [OBJETIVO, "Sesion", "MinutoTotal"]
)

faltantes = [
    c for c in columnas_requeridas
    if c not in df.columns
]

if faltantes:
    raise ValueError(
        f"Faltan columnas: {faltantes}"
    )

# ============================================================
# 3. LIMPIEZA DE DATOS
# ============================================================

df = df[columnas_requeridas].copy()

df[columnas_requeridas] = (
    df[columnas_requeridas]
    .apply(pd.to_numeric, errors="coerce")
)

df = df.dropna(
    subset=columnas_requeridas
)

df = df.sort_values([
    "Sesion",
    "MinutoTotal"
])

df = df.drop_duplicates(
    ["Sesion", "MinutoTotal"],
    keep="last"
)


# Verificar humedad de 0 a 100 %

columnas_humedad = [
    "HumedadSuelo",
    "HumedadSuelo_lag1",
    "HumedadSuelo_lag2",
    OBJETIVO
]

for columna in columnas_humedad:
    df = df[df[columna].between(0, 100)]


# Precipitación no negativa

for columna in [
    "Precipitacion",
    "Precipitacion_lag1",
    "Precipitacion_lag2"
]:
    df = df[df[columna] >= 0]


# Riego: únicamente 0 o 1

for columna in [
    "RiegoActivo",
    "RiegoActivo_lag1",
    "RiegoActivo_lag2"
]:
    df = df[df[columna].isin([0, 1])]


df = df.reset_index(drop=True)

print("\nRegistros válidos:", len(df))


if len(df) < 100:
    raise ValueError(
        "Se necesitan al menos 100 registros válidos. "
        "Se recomiendan 1000 o más con distintos escenarios."
    )


# Verificar diversidad de los datos

for columna in [
    "Temperatura",
    "Precipitacion",
    "RiegoActivo"
]:
    if df[columna].nunique() < 2:
        print(
            f"ADVERTENCIA: {columna} no presenta variaciones."
        )

# ============================================================
# 4. SEPARACIÓN ENTRENAMIENTO Y PRUEBA
# ============================================================

# 80 % entrenamiento
# 20 % prueba
# Mantener el orden cronológico

corte = int(len(df) * 0.90)

# Evitar solapamiento de ventanas en el límite
separacion = 3

df_train = df.iloc[:corte - separacion].copy()
df_test = df.iloc[corte:].copy()


X_train = df_train[variables_modelo]
y_train = df_train[OBJETIVO]

X_test = df_test[variables_modelo]
y_test = df_test[OBJETIVO]


print("\nDistribución de registros:")
print("Entrenamiento:", len(X_train))
print("Prueba:", len(X_test))

print("\nVariables de entrada:", X_train.shape[1])

# ============================================================
# 5. CREAR Y ENTRENAR RANDOM FOREST
# ============================================================

modelo = RandomForestRegressor(

    n_estimators=300,

    max_depth=15,

    min_samples_split=4,

    min_samples_leaf=2,

    random_state=42,

    n_jobs=-1

)


print("\nEntrenando Random Forest...")

modelo.fit(
    X_train,
    y_train
)

print("\nModelo entrenado correctamente.")

# ============================================================
# 6. PREDICCIONES Y EVALUACIÓN
# ============================================================

predicciones = modelo.predict(
    X_test
)


# Error absoluto medio

mae = mean_absolute_error(
    y_test,
    predicciones
)


# Raíz del error cuadrático medio

rmse = math.sqrt(
    mean_squared_error(
        y_test,
        predicciones
    )
)


# Coeficiente de determinación

r2 = r2_score(
    y_test,
    predicciones
)


# Predicción de referencia:
# Suponer que la humedad futura no cambia.

rmse_referencia = math.sqrt(
    mean_squared_error(
        y_test,
        X_test["HumedadSuelo"]
    )
)


print("\n========== RESULTADOS ==========")

print(f"MAE:  {mae:.4f} puntos porcentuales")
print(f"RMSE: {rmse:.4f} puntos porcentuales")
print(f"R²:   {r2:.4f}")

print(
    f"RMSE de referencia: "
    f"{rmse_referencia:.4f}"
)


if rmse >= rmse_referencia:
    print(
        "\nADVERTENCIA: Random Forest no supera "
        "la predicción de humedad constante."
    )
    print(
        "Se recomienda generar escenarios "
        "más variados antes de utilizarlo."
    )

# ============================================================
# 7. GRÁFICA: HUMEDAD REAL VS PREDICHA
# ============================================================

plt.figure(figsize=(11, 4))

plt.plot(
    y_test.to_numpy(),
    label="Humedad real",
    linewidth=1.5
)

plt.plot(
    predicciones,
    label="Humedad predicha",
    linewidth=1.2
)

plt.title(
    "Humedad real y predicha a +10 minutos simulados"
)

plt.xlabel("Muestras de prueba (orden cronológico)")
plt.ylabel("Agua disponible (%)")

plt.legend()
plt.grid(alpha=0.3)
plt.tight_layout()
plt.show()

# ============================================================
# 8. GRÁFICA: IMPORTANCIA DE VARIABLES
# ============================================================

importancias = pd.Series(
    modelo.feature_importances_,
    index=variables_modelo
).sort_values()


plt.figure(figsize=(9, 5))

plt.barh(
    importancias.index,
    importancias.values
)

plt.title(
    "Importancia de variables - Random Forest"
)

plt.xlabel("Importancia relativa")
plt.tight_layout()
plt.show()

# ============================================================
# 9. GUARDAR MODELO ENTRENADO
# ============================================================

paquete_modelo = {

    "modelo": modelo,

    "variables": variables_modelo,

    "paso_minutos": 10,

    "lags": 2,

    "simulador_modelo_version": VERSION_SIMULADOR,

    "sklearn_version": sklearn.__version__,

    "fecha_entrenamiento": datetime.now().isoformat(
        timespec="seconds"
    ),

    "objetivo": (
        "Humedad del suelo a los siguientes "
        "10 minutos simulados"
    ),

    "metricas_prueba": {

        "MAE": float(mae),

        "RMSE": float(rmse),

        "R2": float(r2),

        "RMSE_referencia": float(rmse_referencia),

        "registros_entrenamiento": len(X_train),

        "registros_prueba": len(X_test)
    }
}


nombre_modelo = "modelo_prediccion_humedad.pkl"

joblib.dump(
    paquete_modelo,
    nombre_modelo
)


print("\nModelo guardado correctamente:")
print(nombre_modelo)

print("\nVersión de scikit-learn:")
print(sklearn.__version__)

# ============================================================
# 10. DESCARGAR MODELO
# ============================================================

files.download(
    nombre_modelo
)